    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        meuUsuario.setNomeUsuario(txtNome.getText());
        meuUsuario.setEmailUsuario(txtEmail.getText());
        meuUsuario.setSenhaUsuario(txtSenha.getText());
        
        // Atualizar os perfis de usuario
        if(tbtnFuncionario.isSelected()){
            meuUsuario.setPerfilUsuario("Funcionario");
        } else if (tbtnADM.isSelected()) {
            meuUsuario.setPerfilUsuario("Administrador");
        } else {
            JOptionPane.showMessageDialog(this, "Selecione um perfil");
            return;
        }
        
        UsuarioDAO dao = new UsuarioDAO();
        dao.update(meuUsuario);
        
        limpar();
        preencherTabela();
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int opcao = JOptionPane.showConfirmDialog(null, "Tem certeza que deseja excluir?");
        
        if(opcao == JOptionPane.YES_OPTION){
            UsuarioDAO dao = new UsuarioDAO();
            dao.destroy(meuUsuario);
        }
        
        limpar();
        preencherTabela();
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void tblUsuariosCadastradosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblUsuariosCadastradosMouseClicked
        int linha = tblUsuariosCadastrados.getSelectedRow();
        
        if(linha != -1){
           // JOptionPane.showMessageDialog(null, "Entrou!");
            String id = tblUsuariosCadastrados.getValueAt(linha, 0).toString();
            
            UsuarioDAO dao = new UsuarioDAO();
            meuUsuario = dao.read(Integer.parseInt(id));
            
            // Preencher os campos do formualario
            txtNome.setText(meuUsuario.getNomeUsuario());
            txtEmail.setText(meuUsuario.getEmailUsuario());
            txtSenha.setText(meuUsuario.getSenhaUsuario());
            
            // Carregar o perfil cadastrado
            if(meuUsuario.getPerfilUsuario().equals("Funcionario")){
                tbtnFuncionario.setSelected(true);
            } else if
            (meuUsuario.getPerfilUsuario().equals("Administrador")) {
                tbtnADM.setSelected(true);
            }
            
            btnSalvar.setEnabled(false);
            btnEditar.setEnabled(true);
            btnExcluir.setEnabled(true);
        }
    }//GEN-LAST:event_tblUsuariosCadastradosMouseClicked


