    public void preencherTabela(){
        DefaultTableModel dtm = (DefaultTableModel) tblUsuariosCadastrados.getModel();
        dtm.setRowCount(0);
        UsuarioDAO dao = new UsuarioDAO();
        
        for(Usuario u : dao.read()){
            dtm.addRow(new Object[]{
                u.getIdUsuario(),
                u.getNomeUsuario(),
                u.getEmailUsuario(),
                u.getSenhaUsuario()
            });
        }
    }

