    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        Usuario meuUsuario = new Usuario();

        meuUsuario.setNomeUsuario(txtNome.getText());
        meuUsuario.setEmailUsuario(txtEmail.getText());
        meuUsuario.setSenhaUsuario(txtSenha.getText());

        if (tbtnFuncionario.isSelected()) {
            meuUsuario.setPerfilUsuario("Funcionário");
        } else if (tbtnADM.isSelected()) {
            meuUsuario.setPerfilUsuario("Administrador");
        } else {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Selecione um perfil!"
            );
            return;
        }

        UsuarioDAO dao = new UsuarioDAO();
        dao.create(meuUsuario);

        limpar();
        preencherTabela();
    }//GEN-LAST:event_btnSalvarActionPerformed

