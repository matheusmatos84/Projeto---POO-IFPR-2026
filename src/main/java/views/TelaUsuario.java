    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        // TODO add your handling code here:
        meuUsuario.setNomeUsuario(txtNome.getText());
        meuUsuario.setEmailUsuario(txtEmail.getText());
        meuUsuario.setSenhaUsuario(txtSenha.getText());
        
        UsuarioDAO dao = new UsuarioDAO();
        dao.update(meuUsuario);
        
        limpar();
        preencherTabela();
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        // TODO add your handling code here:
        Usuario meuUsuario = new Usuario();
        
        // Definir os valores dos atributos a partir do formulario
        meuUsuario.setNomeUsuario(txtNome.getText());
        meuUsuario.setEmailUsuario(txtEmail.getText());
        meuUsuario.setSenhaUsuario(txtSenha.getText());
        
        // Instanciar um objeto da classe ClienteDAO
        UsuarioDAO dao = new UsuarioDAO();
        dao.create(meuUsuario);
        
        limpar();
        preencherTabela();
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        // TODO add your handling code here:
        int opcao = JOptionPane.showConfirmDialog(null, "Tem certeza que deseja excluir?");
        
        if(opcao == JOptionPane.YES_OPTION){
            UsuarioDAO dao = new UsuarioDAO();
            dao.destroy(meuUsuario);
        }
        
        limpar();
        preencherTabela();
    }//GEN-LAST:event_btnExcluirActionPerformed

