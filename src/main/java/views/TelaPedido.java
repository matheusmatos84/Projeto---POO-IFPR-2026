    // Metodo para limpar a tela
    public void limpar() {
        txtStatus.setText("");
        txtRetirada.setText("");
        txtDescricao.setText("");
        cmbUsuario.setSelectedIndex(0);
        
        tblPedidos.clearSelection();
        btnSalvar.setEnabled(true);
        btnEditar.setEnabled(false);
        btnExcluir.setEnabled(false);
    }
    
    public void preencherTabela(){
        DefaultTableModel dtm = (DefaultTableModel) tblPedidos.getModel();
        dtm.setRowCount(0);
        PedidoDAO dao = new PedidoDAO();
        
        for(Pedido p : dao.read()){
            dtm.addRow(new Object[]{
                p.getIdPedido(),
                p.getStatusPedido(),
                p.getDataHoraRetirada(),
                p.getObservacoes(),
                p.getUsuario()
            });
        }
    }
    
    // Metodo para preencher o coombo box de Usuario
    public void preencherUsuario(){
        UsuarioDAO dao = new UsuarioDAO();
        
        for(Usuario u : dao.read()){
            cmbUsuario.addItem(u);
        }
    }
    
    public void preencherCliente(){
        ClienteDAO dao = new ClienteDAO();
        
        for(Cliente c : dao.read()){
            cmbCliente.addItem(c);
        }
    }

