    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        Pedido meuPedido = new Pedido();
        
        // Definir os valores dos atributos a partir do formulario
        meuPedido.setStatusPedido(txtStatus.getText());
        meuPedido.setDataHoraRetirada(LocalDateTime.MIN);
        meuPedido.setObservacoes(txtDescricao.getText());
        
        // Para associação com usuario
        meuPedido.setUsuario((Usuario)cmbUsuario.getSelectedItem());
        meuPedido.setCliente((Cliente)cmbCliente.getSelectedItem());
        
        // Instanciar um objeto da classe ClienteDAO
        PedidoDAO dao = new PedidoDAO();
        dao.create(meuPedido);
        
        limpar();
        preencherTabela();
    }//GEN-LAST:event_btnSalvarActionPerformed

